#!/usr/bin/env node
/**
 * Writes src/components/iconData.ts from the `lucide` dev dependency.
 *
 * The Figma redesign draws its icons from Lucide (every `ic:` layer in
 * design/figma/figma.css is a Lucide name, at 20px with a 1.67px stroke), so
 * the app carries Lucide's own geometry rather than a redrawing of it. Only the
 * icons listed here are emitted; add a name and re-run to use another.
 *
 *   node scripts/gen-icons.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

/** Lucide icons used by the design and the app. */
const LUCIDE = [
  'archive', 'arrow-right', 'arrow-up', 'arrow-up-right', 'badge-check', 'banknote', 'battery', 'bell',
  'bell-off', 'bike', 'briefcase', 'building', 'building-2', 'calendar', 'calendar-check', 'calendar-range',
  'camera', 'check', 'chevron-down', 'chevron-left', 'chevron-right', 'circle', 'circle-alert',
  'circle-check', 'circle-dot', 'clipboard', 'clock', 'cloud-off', 'cog', 'copy', 'credit-card', 'crown',
  'disc', 'download', 'droplet', 'droplets', 'ellipsis-vertical', 'eye', 'eye-off', 'factory', 'file',
  'file-check', 'file-clock', 'file-down', 'file-text', 'folder-lock', 'fuel', 'gauge', 'hash', 'heart',
  'history', 'house', 'id-card', 'image', 'info', 'key-round', 'lightbulb', 'link', 'link-2', 'lock',
  'mail', 'map-pin-off', 'menu', 'message-square', 'minus', 'moon', 'package', 'pen-line', 'pencil', 'plus',
  'receipt', 'refresh-cw', 'scan', 'search', 'send', 'settings', 'shield', 'shield-check', 'smartphone',
  'sparkle', 'sparkles', 'square-parking', 'store', 'sun', 'tag', 'thermometer', 'trash', 'trash-2',
  'trending-down', 'trending-up', 'triangle-alert', 'user', 'wallet', 'warehouse', 'wifi-off', 'wind',
  'wrench', 'x', 'zap', 'zap-off',
];

/** Drawn in the design rather than taken from Lucide; geometry read off figma.css. */
const CUSTOM = {
  // `ic:chart-*`: a rounded square with three bars rising to the right.
  chart: [
    ['rect', { width: '18', height: '18', x: '3', y: '3', rx: '2' }],
    ['path', { d: 'M18 9v8' }],
    ['path', { d: 'M13 5v12' }],
    ['path', { d: 'M8 14v3' }],
  ],
  // `ic:tyre-*`: tread ring, hub, four spokes.
  tyre: [
    ['circle', { cx: '12', cy: '12', r: '10' }],
    ['circle', { cx: '12', cy: '12', r: '5' }],
    ['path', { d: 'M12 2v5M12 17v5M2 12h5M17 12h5' }],
  ],
};

const camel = (name) => name.replace(/-([a-z0-9])/g, (_, ch) => ch.toUpperCase());

function readLucide(name) {
  const src = readFileSync(join(root, 'node_modules/lucide/dist/esm/icons', `${name}.js`), 'utf8');
  const body = src.slice(src.indexOf('defaultAttributes,') + 'defaultAttributes,'.length, src.lastIndexOf('];'));
  // The module body is a plain array literal of [tag, attrs] pairs.
  return Function(`"use strict"; return ${body.trim()};`)();
}

const entries = [
  ...LUCIDE.map((name) => [camel(name), readLucide(name)]),
  ...Object.entries(CUSTOM),
].sort(([a], [b]) => a.localeCompare(b));

const lines = entries.map(([key, nodes]) => `  ${key}: ${JSON.stringify(nodes)},`);

writeFileSync(
  join(root, 'src/components/iconData.ts'),
  `// Generated by scripts/gen-icons.mjs from lucide (ISC licence). Do not edit by hand.

export type IconNode = readonly (readonly [string, Readonly<Record<string, string>>])[];

export const ICON_DATA = {
${lines.join('\n')}
} as const satisfies Record<string, IconNode>;

export type IconDataName = keyof typeof ICON_DATA;
`,
);

console.log(`wrote ${entries.length} icons`);
