// ---------------------------------------------------------------------------
// Emit
//
// Two passes, because coverage is a property of the whole suite rather than of
// any one flow. Pass one reads what each recipe already drives; pass two takes
// every id the inventory knows about, and hands the ones nobody claimed to the
// flow that owns their file as a bare assertVisible.
//
// That is what makes this survivable while the screens are being rewritten: a
// renamed id lands on its own screen's flow as an assertion, coverage stays
// whole, and the id is printed as UNCLAIMED so someone gives it a real step.
// ---------------------------------------------------------------------------
const inventory = JSON.parse(readFileSync(join(ROOT, 'e2e/out/inventory.json'), 'utf8'));

/** Every id a block of steps names, literal or regex. */
const idsIn = (steps) => {
  const found = new Set();
  for (const line of steps) {
    for (const m of line.matchAll(/id:\s*"([^"]+)"/g)) found.add(m[1]);
  }
  return found;
};

/** Does anything in `used` satisfy this literal id, or this dynamic prefix? */
const satisfies = (used, id, dynamic) => {
  if (!dynamic) return used.has(id);
  for (const u of used) if (u.startsWith(id) && u.length > id.length) return true;
  return false;
};

// --- pass one: what each recipe already drives, and who owns each file ------
const claimed = new Set();
const owner = new Map();
for (const flow of SCREENS) {
  for (const id of idsIn(flow.steps)) claimed.add(id);
  for (const file of flow.files) if (!owner.has(file)) owner.set(file, flow.name);
}

// --- pass two: hand every unclaimed id to its file's owner ------------------
const fallbackFor = new Map(SCREENS.map((f) => [f.name, []]));
const unclaimed = [];
const unowned = [];

const adopt = (file) => {
  for (const [prefix, flow] of FILE_OWNER_PREFIXES) if (file.startsWith(prefix)) return flow;
  return undefined;
};

for (const screen of inventory.screens) {
  const home = owner.get(screen.file) ?? adopt(screen.file);
  const ids = [
    ...(screen.screenId ? [{ id: screen.screenId, dynamic: false }] : []),
    ...screen.testIds.map((id) => ({ id, dynamic: false })),
    ...screen.dynamicIds
      .map((pattern) => ({ id: pattern.split('${')[0], dynamic: true }))
      .filter((t) => t.id !== ''),
  ];

  for (const target of ids) {
    if (SKIP[target.id] !== undefined) continue;
    if (satisfies(claimed, target.id, target.dynamic)) continue;
    if (home === undefined) {
      unowned.push({ file: screen.file, id: target.id });
      continue;
    }
    fallbackFor.get(home).push(...seeOptional(target.dynamic ? `${target.id}.*` : target.id));
    unclaimed.push({ flow: home, file: screen.file, id: target.dynamic ? `${target.id}\${…}` : target.id });
  }
}

// --- write -----------------------------------------------------------------
mkdirSync(OUT, { recursive: true });
for (const existing of readdirSync(OUT)) {
  if (existing.endsWith('.yaml')) unlinkSync(join(OUT, existing));
}

for (const flow of SCREENS) {
  const fallback = fallbackFor.get(flow.name) ?? [];

  const header = [
    `# ${flow.name}`,
    '#',
    ...flow.why.map((line) => (line === '' ? '#' : `# ${line}`)),
    '#',
    '# GENERATED by e2e/tools/generate.mjs — edit the recipe there, not this file.',
    `# Owns: ${flow.files.join(', ')}`,
    `appId: ${APP_ID}`,
    '---',
  ];

  const body = [
    ...flow.steps,
    ...(fallback.length === 0
      ? []
      : [
          '',
          '# --- ids this recipe does not claim yet: on screen, but not driven ---',
          '# A rename from the redesign lands here. Give each one a real step in',
          '# e2e/tools/generate.mjs and it moves up into the flow above.',
          ...fallback,
        ]),
  ];

  writeFileSync(join(OUT, `${flow.name}.yaml`), `${[...header, ...body].join('\n')}\n`);
}

console.log(`wrote ${SCREENS.length} flows to e2e/generated/`);

if (unowned.length > 0) {
  console.log(`\n${unowned.length} id(s) in files no flow owns — add the file to a flow's \`files\`:`);
  const byFile = new Map();
  for (const u of unowned) {
    if (!byFile.has(u.file)) byFile.set(u.file, []);
    byFile.get(u.file).push(u.id);
  }
  for (const [file, ids] of [...byFile].sort()) console.log(`  ${file}  (${ids.length}: ${ids.join(', ')})`);
}

if (unclaimed.length > 0) {
  console.log(`\n${unclaimed.length} id(s) asserted but not driven — give each a real step:`);
  for (const u of unclaimed.sort((a, b) => a.flow.localeCompare(b.flow))) {
    console.log(`  ${u.flow.padEnd(34)} ${u.id.padEnd(30)} ${u.file}`);
  }
}
