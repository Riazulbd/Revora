/**
 * Reaching the Dashboard from a cold start. Every flow but the signed-out ones
 * begins here, so the tab bar is the single navigation contract under test.
 */
const LAUNCH = [
  '- launchApp:',
  '    clearState: false',
  '- assertVisible:',
  '    id: "screen-dashboard"',
];

/** A signed-out start: the only way to reach welcome / signin / signup. */
const LAUNCH_SIGNED_OUT = [
  '- launchApp:',
  '    clearState: true',
  '- assertVisible:',
  '    id: "screen-welcome"',
];

/** Tap something that sits below the fold. */
const reach = (id) => [
  '- scrollUntilVisible:',
  '    element:',
  `      id: "${id}"`,
  '    direction: DOWN',
];

const tap = (id) => ['- tapOn:', `    id: "${id}"`];
const see = (id) => ['- assertVisible:', `    id: "${id}"`];
/**
 * An id the recipe has not claimed yet. It is optional on purpose: an
 * unclaimed id is one nobody has decided *when* it should be on screen, and a
 * strict assertion about a state nobody has described would abort the flow
 * before the steps that do mean something. The generator prints every one of
 * these, and coverage.mjs counts them as named but never as driven.
 */
const seeOptional = (id) => ['- assertVisible:', `    id: "${id}"`, '    optional: true'];
const gone = (id) => ['- assertNotVisible:', `    id: "${id}"`];
const text = (s) => [`- assertVisible: "${s}"`];
const tapText = (s) => [`- tapOn: "${s}"`];

/** Type into a field that may already hold a value. */
const type = (id, value) => [...tap(id), '- eraseText', `- inputText: "${value}"`];

/** A destructive control: open its dialog, read it, then back out. */
const dialogCancel = (control, dialog) => [
  ...reach(control),
  ...tap(control),
  ...see(dialog),
  ...tap(`${dialog}-cancel`),
  ...gone(dialog),
];

/** The photo chooser is a system Alert; take the Cancel branch. */
const photoCancel = (id) => [
  ...reach(id),
  ...tap(id),
  '- tapOn:',
  '    text: "Cancel"',
  '    optional: true',
];

/** Accept whatever date the Android picker opens on. */
const datePick = (id) => [
  ...reach(id),
  ...tap(id),
  '- tapOn:',
  '    text: "OK"',
  '    optional: true',
];

