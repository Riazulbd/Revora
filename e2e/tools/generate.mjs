#!/usr/bin/env node
/**
 * Writes one Maestro flow per screen, from the live inventory.
 *
 *   node e2e/tools/inventory.mjs      # what the app contains, read from source
 *   node e2e/tools/generate.mjs       # flows that drive all of it
 *   node e2e/tools/coverage.mjs       # proves every id is driven, exits 1 if not
 *
 * Why a generator and not 46 hand-written files: the screens are being
 * rewritten from the redesign right now, so testIDs appear, move and get
 * renamed between one run and the next. A hand-written suite silently stops
 * touching whatever was renamed. This one cannot: every flow is rebuilt from
 * `e2e/out/inventory.json`, and any id the recipe below does not claim is
 * emitted as a bare `assertVisible` and reported as UNCLAIMED, so a rename
 * shows up as work to do rather than as silence.
 *
 * Naming: `<NN>-<screen-id>.yaml`, in the order they must run. A screen whose
 * states cannot coexist — an empty list and a full one, online and offline —
 * gets a `-<phase>` suffix and its own slot in the order. Anything that can
 * only be proved by destroying the fixture is named `*-destructive.yaml` and
 * sorts last.
 *
 * Every flow assumes the fixture from `04-screen-onboarding`: an anonymous
 * rider with one motorcycle, "Audit Bike", opening odometer 4,845 km. Each
 * flow is a separate `launchApp` so a failure does not cascade, but they are
 * ordered: the empty-state flows run before anything is logged.
 */
